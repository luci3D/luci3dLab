#!/usr/bin/env python3
"""Render the luci3D snake as pixel art from a hand-drawn ASCII grid.

The grid is the source of truth: edit it here (or redraw in Aseprite from the
exported PNG). Outputs a 1x master plus scaled PNGs, on transparent and dark
backgrounds, using the brand palette in ../palette/luci3d.gpl.

    python3 brand/tools/make_logo.py
"""
from pathlib import Path
from PIL import Image

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "logo"

# . empty   # body (silkscreen)   o body shade (copper edge)   r tongue
GRID = """
......##############.......
......##############.......
......##..........##.......
......##..........##.......
......##..........##.......
......##..........##.......
......##..........##.......
......##..........##.......
......##..........##.......
......##..........##.......
......##..........##.......
......##..........##.......
......##...##########......
......##...###########.....
......##...##.....##.##....
......##...##.....##..##...
......##...##.....##..##...
......##...##.....##..##...
......##...##.....##..##.#.
......##...##.....##..####.
......##...##.....##.......
......##...##.....##.......
......##...#########.......
......##...#########.......
......##...................
......##...................
...#####...................
...#####...................
.####......................
.####......................
.###.......................
r..........................
.r.........................
"""

PALETTE = {
    "#": (0xF2, 0xEE, 0xE3),  # silkscreen white
    "r": (0xE8, 0x3A, 0x3A),  # tongue red
}
BG_DARK = (0x0B, 0x1A, 0x12)  # solder-mask night green


def render(bg=None):
    rows = [r for r in GRID.strip("\n").splitlines()]
    w, h = max(map(len, rows)), len(rows)
    im = Image.new("RGBA", (w, h), (0, 0, 0, 0) if bg is None else bg + (255,))
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch in PALETTE:
                im.putpixel((x, y), PALETTE[ch] + (255,))
    return im


def main():
    OUT.mkdir(exist_ok=True)
    for name, bg in (("luci3d-snake", None), ("luci3d-snake-dark", BG_DARK)):
        base = render(bg)
        base.save(OUT / f"{name}-1x.png")
        for s in (4, 8, 16):
            base.resize((base.width * s, base.height * s), Image.NEAREST).save(
                OUT / f"{name}-{s}x.png")
    print("wrote", sorted(p.name for p in OUT.glob("*.png")))


if __name__ == "__main__":
    main()
